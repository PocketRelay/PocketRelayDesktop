use crate::services::{ServiceHandle, Services, any_tcp_listener};
use futures::StreamExt;
use pocket_relay_desktop_client_rpc::{DesktopAppService, DesktopAppServices, Pong};
use std::future;
use tarpc::{
    server::{self, Channel, incoming::Incoming},
    tokio_serde::formats::Json,
};

/// Server for handling blaze connections
pub struct RpcServer {}

impl RpcServer {
    pub async fn start(services: Services) -> anyhow::Result<ServiceHandle> {
        let (listener, addr) = any_tcp_listener().await?;

        let service = RpcServerService { services };

        let mut listener = tarpc::serde_transport::tcp::listen_on(listener, Json::default).await?;
        listener.config_mut().max_frame_length(usize::MAX);

        let future = listener
            // Ignore accept errors.
            .filter_map(|r| future::ready(r.ok()))
            .map(server::BaseChannel::with_defaults)
            // Limit channels to 1 per IP.
            .max_channels_per_key(1, |t| t.transport().peer_addr().unwrap().ip())
            // serve is generated by the service attribute. It takes as input any type implementing
            // the generated World trait.
            .map(move |channel| {
                let service = service.clone();
                channel.execute(service.serve()).for_each(spawn)
            })
            // Max 10 channels.
            .buffer_unordered(10)
            .for_each(|_| async {});

        let handle = tokio::spawn(future).abort_handle();

        Ok(ServiceHandle { addr, handle })
    }
}

async fn spawn(fut: impl Future<Output = ()> + Send + 'static) {
    tokio::spawn(fut);
}

#[derive(Clone)]
struct RpcServerService {
    services: Services,
}

impl DesktopAppService for RpcServerService {
    async fn ping(self, _context: tarpc::context::Context, value: u32) -> Pong {
        Pong { value }
    }

    async fn services(self, _context: ::tarpc::context::Context) -> DesktopAppServices {
        DesktopAppServices {
            redirector_address: self.services.redirector.addr,
        }
    }
}
